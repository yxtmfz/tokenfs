#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
from pathlib import Path
from xml.sax.saxutils import escape


CASE_ORDER = ["baseline", "promote", "prefetch", "full"]
CASE_NAMES = {
    "baseline": "baseline：只做本地优先和远端溢写",
    "promote": "promote：加入热点提升",
    "prefetch": "prefetch：加入顺序预取",
    "full": "full：热点提升、顺序预取和淘汰门控联合开启",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Summarize real TokenFS workload speed from strategy matrix outputs."
    )
    parser.add_argument("matrix_dir", help="Directory generated by scripts/strategy_matrix_test.sh")
    parser.add_argument("output_dir", help="Output directory for real-speed summary")
    parser.add_argument(
        "--environment",
        default="TokenFS workload environment",
        help="Human-readable environment label written into the report",
    )
    return parser.parse_args()


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def as_float(value: object, default: float = 0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def workload_bytes(case_dir: Path) -> tuple[float, float, float]:
    summary = case_dir / "summary.csv"
    if not summary.exists():
        return 0.0, 0.0, 0.0
    read_mib = 0.0
    write_mib = 0.0
    for row in read_csv(summary):
        size_mib = as_float(row.get("size_mib"))
        if row.get("operation") == "read":
            read_mib += size_mib
        elif row.get("operation") == "write":
            write_mib += size_mib
    return read_mib, write_mib, read_mib + write_mib


def load_rows(matrix_dir: Path) -> list[dict[str, object]]:
    strategy_summary = matrix_dir / "strategy_summary.csv"
    rows = read_csv(strategy_summary)
    by_case = {row["case"]: row for row in rows}
    ordered = [by_case[name] for name in CASE_ORDER if name in by_case]
    if not ordered:
        return []

    baseline = ordered[0]
    baseline_seconds = as_float(baseline["workload_seconds"])
    baseline_remote_open = as_float(baseline["remote_read_open"])
    baseline_avg_read = as_float(baseline["avg_read_us"])
    _, _, baseline_total_mib = workload_bytes(matrix_dir / baseline["case"])
    baseline_throughput = baseline_total_mib / baseline_seconds if baseline_seconds else 0.0

    output_rows: list[dict[str, object]] = []
    for row in ordered:
        case = row["case"]
        case_dir = matrix_dir / case
        read_mib, write_mib, total_mib = workload_bytes(case_dir)
        seconds = as_float(row["workload_seconds"])
        throughput = total_mib / seconds if seconds else 0.0
        speedup = baseline_seconds / seconds if seconds else 0.0
        throughput_ratio = throughput / baseline_throughput if baseline_throughput else 0.0
        remote_open = as_float(row["remote_read_open"])
        remote_open_reduction = (
            (baseline_remote_open - remote_open) / baseline_remote_open * 100.0
            if baseline_remote_open
            else 0.0
        )
        avg_read = as_float(row["avg_read_us"])
        read_latency_reduction = (
            (baseline_avg_read - avg_read) / baseline_avg_read * 100.0
            if baseline_avg_read
            else 0.0
        )
        output_rows.append(
            {
                "case": case,
                "case_name": CASE_NAMES.get(case, case),
                "read_mib": round(read_mib, 2),
                "write_mib": round(write_mib, 2),
                "total_mib": round(total_mib, 2),
                "wall_time_s": round(seconds, 4),
                "effective_mib_s": round(throughput, 2),
                "speedup_vs_baseline": round(speedup, 4),
                "throughput_vs_baseline": round(throughput_ratio, 4),
                "avg_read_us": round(avg_read, 2),
                "read_latency_reduction_pct": round(read_latency_reduction, 2),
                "avg_write_us": round(as_float(row["avg_write_us"]), 2),
                "local_read_hit_rate_pct": round(as_float(row["read_local_rate_pct"]), 2),
                "remote_read_open": int(remote_open),
                "remote_open_reduction_pct": round(remote_open_reduction, 2),
                "promote_count": int(as_float(row["promote_count"])),
                "prefetch_count": int(as_float(row["prefetch_count"])),
                "evict_count": int(as_float(row["evict_count"])),
                "spill_count": int(as_float(row["spill_count"])),
            }
        )
    return output_rows


def write_summary_csv(rows: list[dict[str, object]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fieldnames = [
        "case",
        "case_name",
        "read_mib",
        "write_mib",
        "total_mib",
        "wall_time_s",
        "effective_mib_s",
        "speedup_vs_baseline",
        "throughput_vs_baseline",
        "avg_read_us",
        "read_latency_reduction_pct",
        "avg_write_us",
        "local_read_hit_rate_pct",
        "remote_read_open",
        "remote_open_reduction_pct",
        "promote_count",
        "prefetch_count",
        "evict_count",
        "spill_count",
    ]
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def svg_bar_chart(
    path: Path,
    title: str,
    rows: list[dict[str, object]],
    key: str,
    unit: str,
    higher_is_better: bool,
) -> None:
    width = 1180
    left = 180
    right = 150
    top = 82
    row_h = 44
    height = top + len(rows) * row_h + 44
    max_value = max((as_float(row[key]) for row in rows), default=1.0)
    max_bar_w = width - left - right
    parts = [
        f"<svg xmlns='http://www.w3.org/2000/svg' width='{width}' height='{height}' viewBox='0 0 {width} {height}'>",
        "<rect width='100%' height='100%' fill='#ffffff'/>",
        f"<text x='24' y='42' font-family='Arial, Helvetica, sans-serif' font-size='26' font-weight='700' fill='#20242b'>{escape(title)}</text>",
        f"<text x='{width - 24}' y='42' text-anchor='end' font-family='Arial, Helvetica, sans-serif' font-size='16' fill='#64748b'>{'越高越好' if higher_is_better else '越低越好'}</text>",
        f"<line x1='24' y1='62' x2='{width - 24}' y2='62' stroke='#d8dee8'/>",
    ]
    for idx, row in enumerate(rows):
        y = top + idx * row_h
        case = str(row["case"])
        value = as_float(row[key])
        bar_w = int(max_bar_w * value / max_value) if max_value else 0
        color = "#2563eb" if case == "full" else "#64748b"
        if case == "baseline":
            color = "#111827"
        parts.extend(
            [
                f"<text x='24' y='{y + 19}' font-family='Menlo, Consolas, monospace' font-size='18' fill='#20242b'>{escape(case)}</text>",
                f"<rect x='{left}' y='{y}' width='{max_bar_w}' height='24' rx='5' fill='#eef2f7'/>",
                f"<rect x='{left}' y='{y}' width='{bar_w}' height='24' rx='5' fill='{color}'/>",
                f"<text x='{left + max_bar_w + 18}' y='{y + 19}' font-family='Arial, Helvetica, sans-serif' font-size='18' fill='#20242b'>{value:.2f}{escape(unit)}</text>",
            ]
        )
    parts.append("</svg>\n")
    path.write_text("\n".join(parts), encoding="utf-8")


def write_report(rows: list[dict[str, object]], output: Path, environment: str) -> None:
    report = output / "real_speed_report.md"
    lines = [
        "# TokenFS 真实速度实验",
        "",
        f"实验环境：{environment}",
        "",
        "本报告只使用真实程序运行产生的 wall-clock 时间、读写吞吐和 TokenFS 指标，不使用成本模型权重。它回答的是：在同一组 token shard workload 下，开启热点提升、顺序预取和联合策略后，系统端到端是否真的更快。",
        "",
        "注意：如果远端后端配置为 `/srv/tokenfs/remote0` 且该目录来自 NVMe-oF 挂载，本报告就是 TokenFS + 真实 NVMe-oF 路径的结果；如果远端后端仍是 `remote-sim` 目录，它只能说明软件策略开销，不能代表真实网络 SSD 性能。",
        "",
        "## 结果表",
        "",
        "| 策略 | 总数据 MiB | 总耗时 s | 有效吞吐 MiB/s | 相对 baseline 加速 | 平均读 us | 读延迟变化 | 本地读命中率 | 远端打开读取 | 远端打开减少 | 后台动作 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        actions = (
            f"promote={row['promote_count']}, "
            f"prefetch={row['prefetch_count']}, "
            f"evict={row['evict_count']}, spill={row['spill_count']}"
        )
        lines.append(
            f"| `{row['case']}` | {row['total_mib']} | {row['wall_time_s']} | "
            f"{row['effective_mib_s']} | {row['speedup_vs_baseline']}x | "
            f"{row['avg_read_us']} | {row['read_latency_reduction_pct']}% | "
            f"{row['local_read_hit_rate_pct']}% | {row['remote_read_open']} | "
            f"{row['remote_open_reduction_pct']}% | {actions} |"
        )

    best_time = min(rows, key=lambda row: as_float(row["wall_time_s"])) if rows else None
    best_throughput = max(rows, key=lambda row: as_float(row["effective_mib_s"])) if rows else None
    full = next((row for row in rows if row["case"] == "full"), None)
    lines.extend(
        [
            "",
            "## 可视化",
            "",
            "![真实总耗时](figures/real_wall_time.svg)",
            "",
            "![真实相对加速比](figures/real_speedup_vs_baseline.svg)",
            "",
            "![真实有效吞吐](figures/real_effective_throughput.svg)",
            "",
            "## 解读",
            "",
        ]
    )
    if best_time:
        lines.append(
            f"- 当前 workload 下总耗时最短的是 `{best_time['case']}`，耗时 `{best_time['wall_time_s']} s`。"
        )
    if best_throughput:
        lines.append(
            f"- 当前 workload 下有效吞吐最高的是 `{best_throughput['case']}`，约 `{best_throughput['effective_mib_s']} MiB/s`。"
        )
    if full:
        speedup = as_float(full["speedup_vs_baseline"])
        if speedup >= 1.0:
            lines.append(f"- `full` 相比 baseline 的真实端到端速度提升为 `{speedup:.4f}x`。")
        else:
            lines.append(
                f"- `full` 相比 baseline 的真实端到端速度为 `{speedup:.4f}x`，说明当前 workload 或参数下策略开销尚未被命中收益抵消。"
            )
            lines.append(
                "- 这不是坏结果，而是后续调参和论文分析的依据：成本模型预测的是长期服务代价，真实速度还受 FUSE 开销、后台任务是否真正触发、远端是否足够慢、热点复用强度等因素影响。"
            )
    lines.extend(
        [
            "",
            "## 论文中怎么使用",
            "",
            "- `objective_cost_per_request` 用来解释控制器的决策质量，是策略层指标。",
            "- `wall_time_s`、`effective_mib_s`、`avg_read_us` 用来回答系统实际快不快，是真实运行指标。",
            "- 如果两者方向不一致，必须优先相信真实速度结果，并回头调整 workload、参数和成本权重。",
        ]
    )
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    args = parse_args()
    matrix_dir = Path(args.matrix_dir)
    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    rows = load_rows(matrix_dir)
    write_summary_csv(rows, output / "real_speed_summary.csv")
    figures = output / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    svg_bar_chart(figures / "real_wall_time.svg", "Real TokenFS wall-clock time", rows, "wall_time_s", "s", False)
    svg_bar_chart(
        figures / "real_speedup_vs_baseline.svg",
        "Real speedup over baseline",
        rows,
        "speedup_vs_baseline",
        "x",
        True,
    )
    svg_bar_chart(
        figures / "real_effective_throughput.svg",
        "Real effective throughput",
        rows,
        "effective_mib_s",
        "MiB/s",
        True,
    )
    write_report(rows, output, args.environment)
    print(f"real speed summary: {output / 'real_speed_summary.csv'}")
    print(f"real speed report:  {output / 'real_speed_report.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
