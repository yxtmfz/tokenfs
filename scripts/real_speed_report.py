#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
from pathlib import Path
from xml.sax.saxutils import escape


CASE_ORDER = ["RemoteOnly", "LocalFirst", "LRU-Local", "LFU-Local", "AURA-Joint"]
CASE_NAMES = {
    "RemoteOnly": "RemoteOnly：全部从远端容量层读取",
    "LocalFirst": "LocalFirst：本地够用优先，本地不足溢写远端",
    "LRU-Local": "LRU-Local：按最近访问时间淘汰",
    "LFU-Local": "LFU-Local：按累计访问次数淘汰",
    "AURA-Joint": "AURA-Joint：价值感知、GPU 亲和和后台动作联合决策",
}
STEADY_REUSE_GROUPS = {
    "hot-rehit-after-promote",
    "sequential-rehit-after-prefetch",
    "cross-gpu-rehit-after-replica",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Summarize real TokenFS workload speed from ablation outputs."
    )
    parser.add_argument("matrix_dir", help="Directory generated by scripts/real_speed_ablation_test.sh")
    parser.add_argument("output_dir", help="Output directory for real-speed summary")
    parser.add_argument(
        "--environment",
        default="TokenFS workload environment",
        help="Human-readable environment label written into the report",
    )
    return parser.parse_args()


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def as_float(value: object, default: float = 0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def workload_bytes(case_dir: Path) -> tuple[float, float, float]:
    summary = case_dir / "summary.csv"
    if not summary.exists():
        return 0.0, 0.0, 0.0
    read_mib = 0.0
    write_mib = 0.0
    for row in read_csv(summary):
        size_mib = as_float(row.get("size_mib"))
        if row.get("operation") == "read":
            read_mib += size_mib
        elif row.get("operation") == "write":
            write_mib += size_mib
    return read_mib, write_mib, read_mib + write_mib


def operation_time(case_dir: Path, operation: str) -> float:
    summary = case_dir / "summary.csv"
    if not summary.exists():
        return 0.0
    seconds = 0.0
    for row in read_csv(summary):
        if row.get("operation") == operation:
            seconds += as_float(row.get("seconds"))
    return seconds


def steady_reuse_stats(case_dir: Path) -> tuple[float, float, float]:
    summary = case_dir / "summary.csv"
    if not summary.exists():
        return 0.0, 0.0, 0.0
    read_mib = 0.0
    seconds = 0.0
    for row in read_csv(summary):
        if row.get("operation") != "read":
            continue
        if row.get("group") not in STEADY_REUSE_GROUPS:
            continue
        read_mib += as_float(row.get("size_mib"))
        seconds += as_float(row.get("seconds"))
    throughput = read_mib / seconds if seconds else 0.0
    return read_mib, seconds, throughput


def load_rows(matrix_dir: Path) -> list[dict[str, object]]:
    strategy_summary = matrix_dir / "strategy_summary.csv"
    rows = read_csv(strategy_summary)
    by_case = {row["case"]: row for row in rows}
    ordered = [by_case[name] for name in CASE_ORDER if name in by_case]
    if not ordered:
        return []

    baseline = ordered[0]
    baseline_seconds = as_float(baseline["workload_seconds"])
    baseline_remote_open = as_float(baseline["remote_read_open"])
    baseline_avg_read = as_float(baseline["avg_read_us"])
    baseline_read_mib, _, baseline_total_mib = workload_bytes(matrix_dir / baseline["case"])
    baseline_read_seconds = operation_time(matrix_dir / baseline["case"], "read")
    _, _, baseline_steady_throughput = steady_reuse_stats(matrix_dir / baseline["case"])
    baseline_throughput = baseline_total_mib / baseline_seconds if baseline_seconds else 0.0
    baseline_read_throughput = (
        baseline_read_mib / baseline_read_seconds if baseline_read_seconds else 0.0
    )

    output_rows: list[dict[str, object]] = []
    for row in ordered:
        case = row["case"]
        case_dir = matrix_dir / case
        read_mib, write_mib, total_mib = workload_bytes(case_dir)
        seconds = as_float(row["workload_seconds"])
        read_seconds = operation_time(case_dir, "read")
        throughput = total_mib / seconds if seconds else 0.0
        read_throughput = read_mib / read_seconds if read_seconds else 0.0
        steady_read_mib, steady_seconds, steady_throughput = steady_reuse_stats(case_dir)
        speedup = baseline_seconds / seconds if seconds else 0.0
        throughput_ratio = throughput / baseline_throughput if baseline_throughput else 0.0
        read_speedup = (
            read_throughput / baseline_read_throughput
            if baseline_read_throughput
            else 0.0
        )
        steady_speedup = (
            steady_throughput / baseline_steady_throughput
            if baseline_steady_throughput
            else 0.0
        )
        remote_open = as_float(row["remote_read_open"])
        remote_open_reduction = (
            (baseline_remote_open - remote_open) / baseline_remote_open * 100.0
            if baseline_remote_open
            else 0.0
        )
        avg_read = as_float(row["avg_read_us"])
        read_latency_reduction = (
            (baseline_avg_read - avg_read) / baseline_avg_read * 100.0
            if baseline_avg_read
            else 0.0
        )
        output_rows.append(
            {
                "case": case,
                "case_name": CASE_NAMES.get(case, case),
                "read_mib": round(read_mib, 2),
                "write_mib": round(write_mib, 2),
                "total_mib": round(total_mib, 2),
                "wall_time_s": round(seconds, 4),
                "effective_mib_s": round(throughput, 2),
                "speedup_vs_baseline": round(speedup, 4),
                "throughput_vs_baseline": round(throughput_ratio, 4),
                "read_time_s": round(read_seconds, 4),
                "read_mib_s": round(read_throughput, 2),
                "read_speedup_vs_baseline": round(read_speedup, 4),
                "steady_reuse_read_mib": round(steady_read_mib, 2),
                "steady_reuse_time_s": round(steady_seconds, 4),
                "steady_reuse_mib_s": round(steady_throughput, 2),
                "steady_reuse_vs_baseline": round(steady_speedup, 4),
                "avg_read_us": round(avg_read, 2),
                "read_latency_reduction_pct": round(read_latency_reduction, 2),
                "avg_write_us": round(as_float(row["avg_write_us"]), 2),
                "local_read_hit_rate_pct": round(as_float(row["read_local_rate_pct"]), 2),
                "remote_read_open": int(remote_open),
                "remote_open_reduction_pct": round(remote_open_reduction, 2),
                "promote_count": int(as_float(row["promote_count"])),
                "prefetch_request_count": int(as_float(row.get("prefetch_request_count", 0))),
                "prefetch_count": int(as_float(row["prefetch_count"])),
                "evict_count": int(as_float(row["evict_count"])),
                "evict_skip_hot": int(as_float(row.get("evict_skip_hot", 0))),
                "spill_count": int(as_float(row["spill_count"])),
                "cross_gpu_replica_create_count": int(
                    as_float(row.get("cross_gpu_replica_create_count", 0))
                ),
                "cross_gpu_local_replica_hit": int(
                    as_float(row.get("cross_gpu_local_replica_hit", 0))
                ),
                "local_cache_create_count": int(as_float(row.get("local_cache_create_count", 0))),
                "local_cache_delete_count": int(as_float(row.get("local_cache_delete_count", 0))),
            }
        )
    return output_rows


def write_summary_csv(rows: list[dict[str, object]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fieldnames = [
        "case",
        "case_name",
        "read_mib",
        "write_mib",
        "total_mib",
        "wall_time_s",
        "effective_mib_s",
        "speedup_vs_baseline",
        "throughput_vs_baseline",
        "read_time_s",
        "read_mib_s",
        "read_speedup_vs_baseline",
        "steady_reuse_read_mib",
        "steady_reuse_time_s",
        "steady_reuse_mib_s",
        "steady_reuse_vs_baseline",
        "avg_read_us",
        "read_latency_reduction_pct",
        "avg_write_us",
        "local_read_hit_rate_pct",
        "remote_read_open",
        "remote_open_reduction_pct",
        "promote_count",
        "prefetch_request_count",
        "prefetch_count",
        "evict_count",
        "evict_skip_hot",
        "spill_count",
        "cross_gpu_replica_create_count",
        "cross_gpu_local_replica_hit",
        "local_cache_create_count",
        "local_cache_delete_count",
    ]
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def svg_bar_chart(
    path: Path,
    title: str,
    rows: list[dict[str, object]],
    key: str,
    unit: str,
    higher_is_better: bool,
) -> None:
    width = 1180
    left = 180
    right = 150
    top = 82
    row_h = 44
    height = top + len(rows) * row_h + 44
    max_value = max((as_float(row[key]) for row in rows), default=1.0)
    max_bar_w = width - left - right
    parts = [
        f"<svg xmlns='http://www.w3.org/2000/svg' width='{width}' height='{height}' viewBox='0 0 {width} {height}'>",
        "<rect width='100%' height='100%' fill='#ffffff'/>",
        f"<text x='24' y='42' font-family='Arial, Helvetica, sans-serif' font-size='26' font-weight='700' fill='#20242b'>{escape(title)}</text>",
        f"<text x='{width - 24}' y='42' text-anchor='end' font-family='Arial, Helvetica, sans-serif' font-size='16' fill='#64748b'>{'越高越好' if higher_is_better else '越低越好'}</text>",
        f"<line x1='24' y1='62' x2='{width - 24}' y2='62' stroke='#d8dee8'/>",
    ]
    for idx, row in enumerate(rows):
        y = top + idx * row_h
        case = str(row["case"])
        value = as_float(row[key])
        bar_w = int(max_bar_w * value / max_value) if max_value else 0
        color = "#2563eb" if case == "AURA-Joint" else "#64748b"
        if case == "RemoteOnly":
            color = "#111827"
        parts.extend(
            [
                f"<text x='24' y='{y + 19}' font-family='Menlo, Consolas, monospace' font-size='18' fill='#20242b'>{escape(case)}</text>",
                f"<rect x='{left}' y='{y}' width='{max_bar_w}' height='24' rx='5' fill='#eef2f7'/>",
                f"<rect x='{left}' y='{y}' width='{bar_w}' height='24' rx='5' fill='{color}'/>",
                f"<text x='{left + max_bar_w + 18}' y='{y + 19}' font-family='Arial, Helvetica, sans-serif' font-size='18' fill='#20242b'>{value:.2f}{escape(unit)}</text>",
            ]
        )
    parts.append("</svg>\n")
    path.write_text("\n".join(parts), encoding="utf-8")


def write_report(rows: list[dict[str, object]], output: Path, environment: str) -> None:
    report = output / "real_speed_report.md"
    lines = [
        "# TokenFS 真实速度实验",
        "",
        f"实验环境：{environment}",
        "",
        "本报告只使用真实程序运行产生的 wall-clock 时间、读写吞吐和 TokenFS 指标，不使用成本模型权重。它回答的是：在同一组 token shard workload 下，AURA-Joint 相比 RemoteOnly、LocalFirst、LRU-Local 和 LFU-Local 是否真的更快。",
        "",
        "注意：`scripts/real_speed_benchmark.sh` 默认会强制检查远端后端已经通过 NVMe-oF 挂载，并要求 `TOKENFS_NVMEOF_PATH_MODE=direct`。只有 `backends[].type = nvmeof`、`nvme_target_ip` 是真实 Target IP、远端根目录已挂载、挂载源为 `/dev/nvme...` 时，才会生成可用于论文的直连 NVMe-oF 端到端速度结果。若显式设置 `TOKENFS_NVMEOF_PATH_MODE=tunnel`，结果只能作为功能验证，不能写成直连性能。",
        "",
        "为避免 Linux 页缓存把远端 NVMe-oF 重复读取伪装成内存命中，真实速度脚本默认在关键阶段以及每次逻辑读取计时前请求清理 OS page cache；清理动作本身只作为 `cache_control` 证据记录，不计入策略读写耗时。这个控制条件不改变 workload 的访问分布，只用于让比较对象回到“本地 SSD 路径 vs 远端 NVMe-oF 路径”。",
        "",
        "## 结果表",
        "",
        "| 策略 | 总数据 MiB | 总耗时 s | 总吞吐 MiB/s | 总吞吐相对 RemoteOnly | 读吞吐 MiB/s | 读吞吐相对 RemoteOnly | 复用阶段吞吐 MiB/s | 复用阶段相对吞吐 | 平均读 us | 本地读命中率 | 远端打开读取 | 远端打开减少 | 后台动作证据 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        actions = (
            f"promote={row['promote_count']}, "
            f"prefetch={row['prefetch_request_count']}/{row['prefetch_count']}, "
            f"evict={row['evict_count']}, skip_hot={row['evict_skip_hot']}, "
            f"xgpu={row['cross_gpu_replica_create_count']}/{row['cross_gpu_local_replica_hit']}, "
            f"spill={row['spill_count']}"
        )
        lines.append(
            f"| `{row['case']}` | {row['total_mib']} | {row['wall_time_s']} | "
            f"{row['effective_mib_s']} | {row['throughput_vs_baseline']}x | "
            f"{row['read_mib_s']} | {row['read_speedup_vs_baseline']}x | "
            f"{row['steady_reuse_mib_s']} | {row['steady_reuse_vs_baseline']}x | "
            f"{row['avg_read_us']} | {row['local_read_hit_rate_pct']}% | {row['remote_read_open']} | "
            f"{row['remote_open_reduction_pct']}% | {actions} |"
        )

    best_time = min(rows, key=lambda row: as_float(row["wall_time_s"])) if rows else None
    best_throughput = max(rows, key=lambda row: as_float(row["effective_mib_s"])) if rows else None
    aura = next((row for row in rows if row["case"] == "AURA-Joint"), None)
    lines.extend(
        [
            "",
            "## 可视化",
            "",
            "![真实总耗时](figures/real_wall_time.svg)",
            "",
            "![真实相对加速比](figures/real_speedup_vs_baseline.svg)",
            "",
            "![真实有效吞吐](figures/real_effective_throughput.svg)",
            "",
            "![真实读吞吐](figures/real_read_throughput.svg)",
            "",
            "![策略生效后复用阶段吞吐](figures/real_steady_reuse_throughput.svg)",
            "",
            "## 解读",
            "",
        ]
    )
    if best_time:
        lines.append(
            f"- 当前 workload 下总耗时最短的是 `{best_time['case']}`，耗时 `{best_time['wall_time_s']} s`。"
        )
    if best_throughput:
        lines.append(
            f"- 当前 workload 下有效吞吐最高的是 `{best_throughput['case']}`，约 `{best_throughput['effective_mib_s']} MiB/s`。"
        )
    if aura:
        speedup = as_float(aura["speedup_vs_baseline"])
        steady_speedup = as_float(aura["steady_reuse_vs_baseline"])
        if speedup >= 1.0:
            lines.append(f"- `AURA-Joint` 相比 `RemoteOnly` 的真实端到端速度提升为 `{speedup:.4f}x`。")
        else:
            lines.append(
                f"- `AURA-Joint` 相比 `RemoteOnly` 的真实端到端速度为 `{speedup:.4f}x`，说明当前 workload 或参数下策略开销尚未被命中收益抵消。"
            )
            lines.append(
                "- 这不是坏结果，而是后续调参和论文分析的依据：成本模型预测的是长期服务代价，真实速度还受 FUSE 开销、后台任务是否真正触发、远端是否足够慢、热点复用强度等因素影响。"
            )
        lines.append(
            f"- 只看策略生效后的热点/预取/跨 GPU 复用阶段，`AURA-Joint` 相对 `RemoteOnly` 的吞吐为 `{steady_speedup:.4f}x`。该指标用于观察后台策略完成后，后续读取收益是否出现。"
        )
    lines.extend(
        [
            "",
            "## 论文中怎么使用",
            "",
            "- `objective_cost_per_request` 用来解释控制器的决策质量，是策略层指标。",
            "- `wall_time_s`、`effective_mib_s`、`avg_read_us` 用来回答系统实际快不快，是真实运行指标。",
            "- 如果两者方向不一致，必须优先相信真实速度结果，并回头检查实现开销、页缓存控制、后台迁移门槛和成本权重。",
        ]
    )
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    args = parse_args()
    matrix_dir = Path(args.matrix_dir)
    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    rows = load_rows(matrix_dir)
    write_summary_csv(rows, output / "real_speed_summary.csv")
    figures = output / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    svg_bar_chart(figures / "real_wall_time.svg", "Real TokenFS wall-clock time", rows, "wall_time_s", "s", False)
    svg_bar_chart(
        figures / "real_speedup_vs_baseline.svg",
        "Real speedup over RemoteOnly",
        rows,
        "speedup_vs_baseline",
        "x",
        True,
    )
    svg_bar_chart(
        figures / "real_effective_throughput.svg",
        "Real effective throughput",
        rows,
        "effective_mib_s",
        "MiB/s",
        True,
    )
    svg_bar_chart(
        figures / "real_read_throughput.svg",
        "Real read throughput",
        rows,
        "read_mib_s",
        "MiB/s",
        True,
    )
    svg_bar_chart(
        figures / "real_steady_reuse_throughput.svg",
        "Steady reuse phase throughput",
        rows,
        "steady_reuse_mib_s",
        "MiB/s",
        True,
    )
    write_report(rows, output, args.environment)
    print(f"real speed summary: {output / 'real_speed_summary.csv'}")
    print(f"real speed report:  {output / 'real_speed_report.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
